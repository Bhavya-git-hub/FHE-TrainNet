"""Write the bundled datasets to `datasets/` as plain CSV.

Run once; the CSVs are then committed and nothing is downloaded at run time. The
sources are the datasets shipped inside scikit-learn itself, so this script needs
no network either.

    python scripts/build_datasets.py

Feature counts are kept small on purpose. Each extra feature is one more
ciphertext-by-ciphertext multiplication per training step, which is the dominant
cost in the encrypted engine.
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.preflight import require_dependencies  # noqa: E402

require_dependencies(script="scripts/build_datasets.py")

import numpy as np  # noqa: E402
from sklearn.datasets import load_breast_cancer, load_iris  # noqa: E402

OUT = ROOT / "datasets"


def _write(name: str, x: np.ndarray, y: np.ndarray, feature_names: list[str]) -> Path:
    path = OUT / f"{name}.csv"
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow([*feature_names, "label"])
        for row, label in zip(x, y):
            writer.writerow([f"{v:.6g}" for v in row] + [int(label)])
    print(f"  {path.relative_to(ROOT)}  {x.shape[0]} samples x {x.shape[1]} features")
    return path


def build_iris_binary() -> None:
    """Versicolor vs virginica - the genuinely non-trivial half of iris."""
    data = load_iris()
    mask = data.target > 0
    x = data.data[mask]
    y = (data.target[mask] == 2).astype(int)
    names = [n.replace(" (cm)", "").replace(" ", "_") for n in data.feature_names]
    _write("iris_binary", x, y, names)


def build_breast_cancer_top8() -> None:
    """Breast cancer restricted to eight features by univariate separation.

    Selection uses only the absolute standardized mean difference between classes,
    computed over the whole file. That is a documented property of the bundled
    dataset, not a model fitted to a test set.
    """
    data = load_breast_cancer()
    x, y = data.data, data.target
    pos, neg = x[y == 1], x[y == 0]
    spread = x.std(axis=0)
    spread = np.where(spread < 1e-12, 1.0, spread)
    separation = np.abs(pos.mean(axis=0) - neg.mean(axis=0)) / spread
    keep = np.argsort(separation)[::-1][:8]
    keep = np.sort(keep)
    names = [data.feature_names[i].replace(" ", "_") for i in keep]
    _write("breast_cancer_top8", x[:, keep], y, names)


def build_moons_like() -> None:
    """A small, reproducible, non-linearly separable synthetic set.

    Present so the polynomial activation has something to do that a purely linear
    model cannot: it makes the accuracy comparison between plaintext and encrypted
    training informative rather than trivially saturated.
    """
    rng = np.random.default_rng(20260916)
    n = 90
    t_a = rng.uniform(0, np.pi, n)
    t_b = rng.uniform(0, np.pi, n)
    ax = np.c_[np.cos(t_a), np.sin(t_a)] + rng.normal(0, 0.13, (n, 2))
    bx = np.c_[1 - np.cos(t_b), 0.5 - np.sin(t_b)] + rng.normal(0, 0.13, (n, 2))
    x = np.vstack([ax, bx])
    y = np.r_[np.zeros(n, dtype=int), np.ones(n, dtype=int)]
    order = rng.permutation(len(y))
    _write("two_moons", x[order], y[order], ["x1", "x2"])


def write_card() -> None:
    (OUT / "README.md").write_text(
        """# Bundled datasets

Generated by `scripts/build_datasets.py`. Committed so that no download happens at
run time and so the exact bytes behind a published result are in the repository.

| File | Samples | Features | Origin |
|---|---|---|---|
| `iris_binary.csv` | 100 | 4 | scikit-learn `load_iris`, versicolor vs virginica |
| `breast_cancer_top8.csv` | 569 | 8 | scikit-learn `load_breast_cancer`, 8 most separable features |
| `two_moons.csv` | 180 | 2 | synthetic, seed 20260916, non-linearly separable |

## Contract

One header row. Numeric feature columns. A final column named `label` holding only
`0` or `1`. `src.data.loader.load_dataset` validates all of this and names the
offending line when it fails.

## Using your own data

Drop a CSV meeting the contract into this directory; it appears in the dashboard's
dataset list automatically. Keep the feature count small - every feature costs one
ciphertext-by-ciphertext multiplication per training step.

## Preprocessing

`src.data.loader.prepare` standardizes with training-set statistics and then clips
to `feature_range` (default 3.0). The clip is a correctness measure, not tidiness:
the polynomial activation is faithful only on a bounded interval, and outside it
the approximation returns a wrong value without raising. The fraction of values
clipped is recorded on the split and reported in results.
""",
        encoding="utf-8",
    )


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    print("Writing bundled datasets:")
    build_iris_binary()
    build_breast_cancer_top8()
    build_moons_like()
    write_card()
    print(f"  {(OUT / 'README.md').relative_to(ROOT)}  (dataset card)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
